"""
全局强约束：所有模型调用（含 subagent 与二次提炼层）的唯一来源。

每一条都对应一次已核实的真实错误（见 knowledgeBase/doc/2026-08-07 核验记录），
不是预防性设计：
  - C1/C2 ← 模型自加章节：prompt 只列 4 项，输出 7 节，自加的两节造假密度 11.4%，
    是 prompt 要求章节的 11 倍。标题一旦立起来就必须填内容，无内容则编。
  - C3 ← 编造字面量：产出过 huawei.com/Ascend1980（真实为 ascend-1980，全仓 0 次），
    成因是从 Ascend910 借用命名风格做插值。
  - C4 ← 无差异时造差异：0.13.0 与 0.14.2 的 values.yaml 实际只差 4 行
    （行尾空格 + 末尾换行），模型仍编出 metrics/日志/nodeSelector 的版本演进叙事。
  - C5 ← 作用域误配：把 vendored 子组件的约束当成全仓要求
    （git-cdn 容器内的 python3.12 路径 → 全仓 Python 版本要求）。
  - C8/C9 ← 擅自遗弃与截断：3000 字符硬截断吃掉 MK 29.8% 的内容且无人知晓。
"""

# 事实纪律：约束模型「说什么」。所有调用模型的地方都必须注入。
FACT_DISCIPLINE = """
## 事实纪律（违反任一条即为不合格输出）

C3. **字面量必须逐字来自输入。** 资源键名、版本号、镜像地址、仓库 URL、路径、端口、
    配置键、环境变量名等任何精确字符串，只能从输入中原样复制。禁止依据命名风格
    推断、补全或修正。输入中没有这个值，就不要写这个值。

C4. **无差异时必须明说无差异。** 多个对象实质相同时直接写「配置相同」，禁止为了
    让叙述显得充实而编造差异、演进或阶段划分。

C5. **不得放大作用域。** 子模块、vendored 依赖或单个文件中的约束，不得表述为整个
    项目的要求。引用时必须说明该结论的适用范围。

C6. **无依据处留空并标注。** 找不到依据的条目，写「输入中未提供，需查阅源码确认」，
    禁止用常见默认值、经验值或合理猜测填充。没有解读到就是没有解读到。

C7. **每条事实性断言都要给出来源文件路径。** 给不出来源的断言不要写。
"""

# 契约纪律：约束模型「输出什么形状」。
CONTRACT_DISCIPLINE = """
## 契约纪律（违反任一条即为不合格输出）

C1. **章节结构是契约，不是下限。** 只输出「要求」中列出的章节，编号与标题必须与要求
    一一对应。禁止新增、合并、拆分或重排章节。即使你认为某个额外章节有价值，也不要加。

C2. **禁止自行引入对比维度。** 不要主动生成「版本演进」「参数对比」「优劣对比」这类
    要求中未指定的表格或图示。
"""

# 范围纪律：约束模型「做什么」。禁止擅自决定丢弃/截断，禁止越界执行。
SCOPE_DISCIPLINE = """
## 范围纪律（违反任一条即为不合格输出）

C8. **禁止擅自遗弃或截断。** 不得因为输入过多而自行跳过、抽样、省略或截断任何输入。
    确实超出处理能力时，停止输出正文，改为输出一份「需用户决策」说明：列出全部候选、
    数量、以及你建议的取舍方案，等待决策。绝不静默丢数据。

C9. **只做被要求的事。** 完成要求范围内的工作后立即停止，不做要求之外的任何分析、
    优化、重构或建议。不修改任何未被指定的文件。
"""

# 行文纪律：约束交付物「读起来像什么」。
#
# 这组约束来自一次真实的返工：产出的报告事实全部正确，但几乎每句话都挂着
# 「（来源：raw.json content，path=...）」「（来源：verify.json conflicts[K02]
# .corrected_fact，修正 raw.json 中"..."的原始描述）」，结构表里还有「详略：core
# （723 个文件，已由代表样本覆盖）」这类流水线内部决策。信息量大但杂糅，人读不下去。
#
# 根因是 C7「每条断言给出来源」被理解成了「每句话都要贴溯源标签」。溯源必须可查，
# 但它的位置是 check.md 和中间产物，不是交付文档的正文。
PROSE_DISCIPLINE = """
## 行文纪律（交付物是给人看的）

C10. **禁止在正文里出现流水线内部名词。** `raw.json`、`verify.json`、
     `preprocess.json`、`interpret_inputs`、`rule_facts`、`core/auxiliary`、
     「代表样本」「已修正」「原始描述」等一律不得出现。读者要的是结论，
     不是结论的生产过程。修正history写在 check.md 里，正文只写修正后的事实。

C11. **来源路径只在它本身就是内容时出现。** 「修改 `scripts/argocd-app-lint.sh`」
     里的路径是内容，保留；「（来源：`raw.json` content，path=`README.md`）」
     是溯源标签，删掉。需要标注依据时，用行内代码写出真实的仓库文件路径即可，
     不要写产物名。

C12. **一句话只说一件事。** 不要把「是什么 + 在哪 + 谁改的 + 原来错在哪」塞进
     同一个句子。超过三个逗号的句子拆开。

C13. **结构要能被扫读。** 表格优于长段落，短句优于从句嵌套。标题层级不超过三层。
     同类条目用表格，不要用 19 条平铺的编号列表。

C14. **凝练。** 同一事实只说一次。删掉「值得注意的是」「需要说明的是」这类无信息
     的过渡。宁可少写，不要为了显得完整而重复。
"""

ALL_DISCIPLINES = (FACT_DISCIPLINE + CONTRACT_DISCIPLINE + SCOPE_DISCIPLINE
                   + PROSE_DISCIPLINE)


def build_constraints(*, fact: bool = True, contract: bool = True,
                      scope: bool = True, prose: bool = True) -> str:
    """按需拼装约束段落。默认全上。"""
    parts = []
    if fact:
        parts.append(FACT_DISCIPLINE)
    if contract:
        parts.append(CONTRACT_DISCIPLINE)
    if scope:
        parts.append(SCOPE_DISCIPLINE)
    if prose:
        parts.append(PROSE_DISCIPLINE)
    return "".join(parts)
